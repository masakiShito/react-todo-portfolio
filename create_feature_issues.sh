#!/bin/bash

REPO="masakiShito/react-todo-portfolio"
LABEL="enhancement"
ASSIGNEE="masakiShito"

# タイトルと説明をペアで定義
FEATURES=(
  "🧭 タスク詳細ページの作成|タスクの個別ビューを作成し、コメント・履歴表示を可能にする。"
  "🗂️ 表示順を期限優先に|タスク一覧を期限→優先度→作成日でソート切替できるようにする。"
  "🔍 検索機能の追加|タイトル・説明・タグでリアルタイム検索できるようにする。"
  "🏷️ タグの複数選択・管理|タグの作成・編集・削除・複数選択を可能にする。"
  "🔁 繰り返しタスク|毎日・毎週・毎月の繰り返しタスクと終了条件を設定できるようにする。"
  "⏰ 期限リマインダー通知|ブラウザ/PWA通知で期限前にリマインド通知を出す。"
  "✅ 一括操作機能|複数タスクをまとめて完了・削除・タグ付けできるようにする。"
  "🕓 編集履歴と復元|タスク変更履歴を保存し、元に戻す/やり直しを可能にする。"
  "📦 アーカイブ機能|完了済みタスクをアーカイブに退避し、復元も可能にする。"
  "✏️ インライン編集の強化|Enter保存・ESCキャンセル・外側クリック確定を実装する。"
  "🌍 i18n対応|UIテキストを日本語/英語に切り替えできるようにする。"
  "📱 PWA化対応|オフライン・インストール対応を行い、PWA対応する。"
  "📤 共有/エクスポート機能|タスクをCSV/JSONで出力、URL共有を可能にする。"
  "📆 カスタムビュー（看板・カレンダー）|看板ボードやカレンダーでタスクを可視化する。"
  "♿ アクセシビリティ改善|ショートカットキーやスクリーンリーダー対応を強化する。"
)

# ループ処理
for ITEM in "${FEATURES[@]}"; do
  TITLE="${ITEM%%|*}"
  DESCRIPTION="${ITEM#*|}"
  echo "🚀 Creating issue: $TITLE"
  
  gh issue create \
    --repo "$REPO" \
    --title "[Feature]: $TITLE" \
    --body "$DESCRIPTION" \
    --label "$LABEL" \
    --assignee "$ASSIGNEE"
done
